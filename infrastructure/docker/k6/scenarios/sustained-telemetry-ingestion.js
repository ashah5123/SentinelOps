// Scenario: sustained alert/telemetry ingestion (Phase 15 load-testing expansion).
//
// Alertmanager-format webhook delivery is this platform's actual "telemetry ingestion" surface
// (see docs/development/alert-ingestion.md) — there is no separate raw-telemetry HTTP endpoint.
// Each iteration posts one firing alert with a unique fingerprint at a sustained rate for the
// whole run, distinct from burst-recovery.js's short steep spike: this measures steady-state
// ingestion throughput/latency, not saturation behavior.
//
// Configurable via env vars: BENCHMARK_RATE (default 20, requests/sec), BENCHMARK_DURATION
// (default 2m), ALERTS_ALERTMANAGER_SHARED_TOKEN (required — same static bearer token
// infrastructure/docker/scripts/alert-demo.sh uses).
import http from "k6/http";
import { check } from "k6";
import { Trend } from "k6/metrics";
import { BASE_URL, RUN_ID } from "../lib/common.js";

const RATE = parseInt(__ENV.BENCHMARK_RATE || "20", 10);
const DURATION = __ENV.BENCHMARK_DURATION || "2m";
const TOKEN = __ENV.ALERTS_ALERTMANAGER_SHARED_TOKEN;

export const ingestLatency = new Trend("telemetry_ingest_duration", true);

export const options = {
  scenarios: {
    sustained_telemetry_ingestion: {
      executor: "constant-arrival-rate",
      rate: RATE,
      timeUnit: "1s",
      duration: DURATION,
      preAllocatedVUs: Math.max(10, Math.ceil(RATE / 2)),
      maxVUs: RATE * 2,
    },
  },
  thresholds: {
    http_req_failed: ["rate<0.02"],
    telemetry_ingest_duration: ["p(95)<1000"],
  },
};

export default function () {
  if (!TOKEN) {
    throw new Error("ALERTS_ALERTMANAGER_SHARED_TOKEN is required for this scenario");
  }
  const fingerprint = `sustained-${RUN_ID}-${__VU}-${__ITER}-${Date.now()}`;
  const startsAt = new Date().toISOString();
  const payload = JSON.stringify({
    version: "4",
    status: "firing",
    receiver: "sentinelops-incident-service",
    alerts: [
      {
        status: "firing",
        labels: {
          alertname: "SustainedLoadTest",
          severity: "warning",
          service: "k6-load-test",
          environment: "local",
          instance: fingerprint,
        },
        annotations: {
          summary: "Synthetic sustained-ingestion load-test alert",
          description: "Generated by sustained-telemetry-ingestion.js",
        },
        startsAt,
        endsAt: "0001-01-01T00:00:00Z",
        generatorURL: "http://prometheus:9090/graph",
        fingerprint,
      },
    ],
  });

  const res = http.post(`${BASE_URL}/api/v1/alerts/webhooks/alertmanager`, payload, {
    headers: {
      Authorization: `Bearer ${TOKEN}`,
      "Content-Type": "application/json",
    },
    tags: { name: "ingest-alert" },
  });

  ingestLatency.add(res.timings.duration);
  check(res, { "alert accepted": (r) => r.status === 202 });
}
